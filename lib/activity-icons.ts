export type ActivityIcon = keyof typeof ACTIVITY_ICONS;

export const DEFAULT_ACTIVITY_ICON: ActivityIcon = "party-popper";

export function isActivityIcon(key: string): key is ActivityIcon {
  return Object.hasOwn(ACTIVITY_ICONS, key);
}

const FILLER = new Set(["a", "an", "and", "at", "for", "in", "my", "of", "on", "the", "to", "with"]);

// A search word and its singulars, so "puzzles" finds "puzzle" and "berries" finds "berry".
const forms = (word: string) => [word, word.replace(/ies$/, "y"), word.replace(/(?<=[^s]{3})s$/, "")];

/** How well one search word fits an icon's text: a whole word beats the start of one, which beats the middle. */
function fit(text: string, word: string) {
  if (new RegExp(`\\b${word}s?\\b`).test(text)) return 3;
  if (new RegExp(`\\b${word}`).test(text)) return 2;
  return text.includes(word) ? 1 : 0;
}

/**
 * Icons for a search, most relevant first: those that fit more of the query's words, and fit them
 * better, come first, then picker order. An empty query returns every icon.
 */
export function searchIcons(query: string) {
  const keys = Object.keys(ACTIVITY_ICONS) as ActivityIcon[];
  const words = query.toLowerCase().replace(/'/g, "").split(/[^a-z0-9]+/).filter((w) => w && !FILLER.has(w));
  if (!words.length) return keys;
  return keys
    .map((key) => {
      const text = `${key.replace(/-/g, " ")} ${ACTIVITY_ICONS[key]}`;
      return { key, score: words.reduce((sum, w) => sum + Math.max(...forms(w).map((f) => fit(text, f))), 0) };
    })
    .filter((m) => m.score > 0)
    .sort((a, b) => b.score - a.score)
    .map((m) => m.key);
}
